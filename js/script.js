function toggleMusic(){
    let music = document.getElementById("backgroundMusic");
    let button = document.getElementById("musicButton");

    if (music.paused == true){
        music.volume = 0.3;
        music.play();
        button.innerHTML = "Music On";
    }
    else{
        music.pause();
        button.innerHTML = "Music Off";
    }
}